/**
 * Design-token → ECharts theme adapter.
 *
 * Single source: tools/docgen/assets/tokens.json (itself vendored from the
 * marketing Atlas brand.css v3.3). This module never defines a color of its
 * own — every value is read from the token file, so re-vendoring the Atlas
 * propagates here on the next `npm run build:themes`.
 *
 * Reskin law (RESKINNING_AND_THEME_POLICY.md): themes may change appearance,
 * never data semantics. Severity colors are semantic and reserved — they are
 * exposed as `severity` for presets that encode actual severity, and must not
 * be used as a decorative palette.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ENGINE_ROOT = join(HERE, "..", "..");
const DOCGEN_TOKENS = join(ENGINE_ROOT, "..", "docgen", "assets", "tokens.json");
const THEMES_DIR = join(ENGINE_ROOT, "themes");

export function loadTokens() {
  return JSON.parse(readFileSync(DOCGEN_TOKENS, "utf8"));
}

/**
 * The OPAQUE ground a theme paints on, by theme name (`OPEN_GATES.md` OG-50).
 *
 * Every rendered SVG sets `backgroundColor: "transparent"` on purpose, so a chart inherits the
 * ground of whatever it is placed into. **A raster has nothing to inherit from.** `renderPNG`
 * therefore has to be told a ground, and it used to bake the literal dark `#060608` regardless of
 * theme — so a PNG of a light-theme chart came out dark, with light-theme ink on it.
 *
 * Read from the token file like everything else here; this module never defines a colour of its
 * own. `document-theme` returns `null` because a document chart follows the HOST document's
 * palette, which is a runtime CSS decision a PNG cannot observe — the caller must say which theme
 * it is exporting for, and `renderPNG` records a warning when it has to guess.
 */
export function opaqueGround(themeName) {
  const t = loadTokens();
  switch (themeName) {
    case "project-theme-light":
      return t.grounds_light.night;
    case "print-theme":
      return "#FFFFFF";
    case "document-theme":
      return null;
    default: // project-theme / project-theme-dark — the native dark ground
      return t.grounds_dark.night;
  }
}

/** Categorical palette — same six Atlas hues, same order, as docgen charts.py. */
export function categoricalPalette(t) {
  const b = t.brand;
  return [b["shield-hi"], b["bronze-hi"], b["gold-hi"], b.verify, b["ember-hi"], b["shield-dim"]];
}

/** Heatmap interpolation ramp — literal RGB, mirrors docgen charts.py. */
export const HEAT_RAMP = ["rgb(15,32,64)", "rgb(74,127,193)", "rgb(237,184,74)"];

const FONT_BODY = 'Inter, system-ui, sans-serif'; // unquoted: quoted names break ECharts SSR SVG font attributes
const FONT_DISPLAY = 'Space Grotesk, system-ui, sans-serif';
const FONT_MONO = 'JetBrains Mono, ui-monospace, monospace';

function buildTheme(t, mode /* "dark" | "light" | "print" | "document" */) {
  const dark = mode === "dark";
  // "document" is the mode for SVG that is INLINED into a docgen document. Its ink and hairline
  // values are CSS custom properties rather than literal hex, so the chart follows the document's
  // palette exactly like every native docgen figure does — including the runtime theme toggle and
  // the `prefers-color-scheme: light` default. Baking hex here is what made every chart render
  // light-on-dark inside a light document: the figure could not follow a theme decided after the
  // SVG was written. Only inks and hairlines are substituted, because the categorical palette is
  // already mode-independent (it comes from `t.brand`, not from grounds/inks).
  const doc = mode === "document";
  const grounds = dark ? t.grounds_dark : t.grounds_light;
  const rawInks = dark ? t.inks_dark : t.inks_light;
  const inks = doc
    ? { ...rawInks, bone: "var(--fg)", ash: "var(--mute)", steel: "var(--mute)" }
    : rawInks;
  const hairline = doc
    ? "var(--faint)"
    : dark
      ? "rgba(234,238,245,0.10)"
      : "rgba(11,14,20,0.12)";
  const hairlineStrong = doc
    ? "var(--faint)"
    : dark
      ? "rgba(234,238,245,0.18)"
      : "rgba(11,14,20,0.22)";

  return {
    _provenance: `Generated by adapters/echarts/theme-adapter.mjs from tools/docgen/assets/tokens.json (Atlas brand.css v3.3). Do not hand-edit — re-run \`npm run build:themes\`.`,
    _mode: mode,
    color: categoricalPalette(t),
    backgroundColor: mode === "print" ? "#FFFFFF" : "transparent",
    textStyle: { fontFamily: FONT_BODY, color: inks.bone, fontSize: 12 },
    title: {
      textStyle: { fontFamily: FONT_DISPLAY, color: inks.bone, fontSize: 16, fontWeight: 600 },
      subtextStyle: { fontFamily: FONT_BODY, color: inks.ash, fontSize: 12 },
    },
    legend: {
      textStyle: { color: inks.ash, fontFamily: FONT_BODY, fontSize: 11 },
      pageTextStyle: { color: inks.ash },
    },
    tooltip: {
      backgroundColor: grounds["steel-2"],
      borderColor: hairlineStrong,
      textStyle: { color: inks.bone, fontFamily: FONT_BODY, fontSize: 12 },
    },
    grid: { borderColor: hairline },
    categoryAxis: {
      axisLine: { lineStyle: { color: hairlineStrong } },
      axisTick: { lineStyle: { color: hairlineStrong } },
      axisLabel: { color: inks.ash, fontFamily: FONT_BODY, fontSize: 11 },
      splitLine: { show: false },
    },
    valueAxis: {
      axisLine: { show: false },
      axisTick: { show: false },
      axisLabel: { color: inks.ash, fontFamily: FONT_MONO, fontSize: 10 },
      splitLine: { lineStyle: { color: hairline } },
    },
    timeAxis: {
      axisLine: { lineStyle: { color: hairlineStrong } },
      axisLabel: { color: inks.ash, fontFamily: FONT_MONO, fontSize: 10 },
      splitLine: { show: false },
    },
    logAxis: {
      axisLabel: { color: inks.ash, fontFamily: FONT_MONO, fontSize: 10 },
      splitLine: { lineStyle: { color: hairline } },
    },
    bar: { itemStyle: { borderRadius: [2, 2, 0, 0] } },
    line: { symbolSize: 7, lineStyle: { width: 2.5 }, smooth: false },
    pie: { label: { color: inks.ash, fontFamily: FONT_BODY, fontSize: 11 } },
    heatmap: { itemStyle: { borderColor: doc ? "var(--bg)" : grounds.night, borderWidth: 1 } },
    graph: {
      lineStyle: { color: hairlineStrong },
      label: { color: inks.bone, fontFamily: FONT_BODY, fontSize: 11 },
    },
    sankey: {
      lineStyle: { color: "gradient", opacity: dark ? 0.25 : 0.35 },
      label: { color: inks.bone, fontFamily: FONT_BODY, fontSize: 11 },
    },
    // Semantic lattices — reserved, not decorative (severity meaning only).
    severity: { ...t.severity },
    semantic: {
      verify: t.brand.verify,
      ember: t.brand.ember,
      gold: t.brand.gold,
      shield: t.brand.shield,
      inks,
      grounds,
      hairline,
      hairlineStrong,
      heatRamp: HEAT_RAMP,
    },
  };
}

export function buildAllThemes() {
  const t = loadTokens();
  return {
    // P8-123: `project-theme` and `project-theme-dark` are DELIBERATE, byte-identical aliases —
    // both call buildTheme(t, "dark") — so the reskin regression test's distinct-SVG count is 4,
    // not 5 (tests/reskin.test.mjs, RESKINNING_AND_THEME_POLICY.md). `project-theme` is the
    // native/default name; `project-theme-dark` exists so a caller can be explicit about which
    // mode it wants without an alias-resolution step. Not drift — recorded so it reads as intended.
    "project-theme": buildTheme(t, "dark"), // native ground is dark, matching docgen
    "project-theme-dark": buildTheme(t, "dark"),
    "project-theme-light": buildTheme(t, "light"),
    "print-theme": buildTheme(t, "print"),
    // Inlined-into-a-document variant; see the "document" branch in buildTheme().
    "document-theme": buildTheme(t, "document"),
  };
}

// P8-082/P8-084: themes/*.json on disk is WRITE-ONLY from this engine's own point of view —
// `themes()` in render.mjs calls buildAllThemes() fresh, in memory, and never reads these files
// back (confirmed: no `readFileSync` of themes/ anywhere in this tree). The tracked snapshot
// exists for (a) a host project or human inspecting the palette without running node, and (b)
// tools/docgen's build-cache fingerprint. `themeDiskRecord` labels that plainly so the tracked
// copy does not read as a live dependency it isn't; the label is added only on the disk copy —
// never on the object handed to `echarts.registerTheme()`, so it cannot affect a single rendered
// pixel. See RESKINNING_AND_THEME_POLICY.md for the corrected authority chain.
export function themeDiskRecord(theme) {
  return {
    _readme: "GENERATED snapshot for human inspection / tools/docgen build-cache fingerprinting " +
      "only. This engine's own runtime (adapters/echarts/render.mjs `themes()`) recomputes themes " +
      "in memory from buildAllThemes() at render time and never reads this file back — hand-editing " +
      "it has zero effect on any render. Re-run `npm run build:themes` after re-vendoring the Atlas.",
    ...theme,
  };
}

// THE one description of what `themes/` contains: `{ filename -> exact file contents }`.
//
// It exists because the health check that verifies these files (`BUILD-04`, added the same day as
// `themeDiskRecord`) had its OWN copy of the serialisation below, and the two drifted within hours:
// `themeDiskRecord`'s `_readme` landed here and the checker still compared against the un-labelled
// object, so all six tracked files reported as drift on a tree where nothing had drifted. That is
// `RULES.md` Rule 2 — a fact restated in a second place — expressed in code instead of prose.
// The writer and the verifier now call this, so a change to the on-disk shape cannot desynchronise
// them again: there is only one shape.
export function buildThemeFiles() {
  const files = {};
  const themes = buildAllThemes();
  for (const [name, theme] of Object.entries(themes)) {
    files[`${name}.json`] = JSON.stringify(themeDiskRecord(theme), null, 2) + "\n";
  }
  files["tokens.json"] = JSON.stringify(
    {
      _provenance: "GENERATED copy of tools/docgen/assets/tokens.json for engine consumers. Source of truth is docgen; re-run `npm run build:themes` after re-vendoring the Atlas.",
      _readme: "Exposed for HOST-PROJECT consumers only — this engine's own code reads tokens.json " +
        "from tools/docgen/assets/ directly (loadTokens() above), never from this copy.",
      ...loadTokens(),
    },
    null,
    2,
  ) + "\n";
  return files;
}

if (process.argv.includes("--build")) {
  mkdirSync(THEMES_DIR, { recursive: true });
  const files = buildThemeFiles();
  for (const [filename, contents] of Object.entries(files)) {
    writeFileSync(join(THEMES_DIR, filename), contents);
  }
  console.log(`themes built: ${Object.keys(files).join(", ")} → ${THEMES_DIR}`);
}
