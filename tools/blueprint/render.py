"""Render the derived model into the artifacts an agent actually reads.

Design constraint, stated because it is the whole point: **``SYSTEM.md`` must stay small.** It is an
index, not a document. An orientation map that costs as much to read as the tree it describes has
saved nothing. Every section here answers one question an agent asks in its first minute — *what is
here, what depends on what, what guards it, what is still open, where do I look next* — and answers
it with addresses rather than prose.
"""

from __future__ import annotations

import json
from typing import Any

_TOP_CORE = 12
_MAX_PACKAGE_ROWS = 20


_NUMBER_WORDS = ("zero", "one", "two", "three", "four", "five", "six", "seven", "eight")


def _number_word(n: int) -> str:
    """Spell a small count, so a heading cannot disagree with the list beneath it.

    It did: the guard-registration heading said "two edits" directly above three items, because the
    sentence was hardcoded while the list was derived. Deriving both from one number is the only
    version that cannot drift — `RULES.md` Rule 2 applied to a renderer.
    """
    return _NUMBER_WORDS[n] if 0 <= n < len(_NUMBER_WORDS) else str(n)


def _trim(text: str, limit: int) -> str:
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def render_mermaid(model: dict[str, Any]) -> str:
    """Package-level dependency graph.

    Deliberately PACKAGE level, not module level: 76 nodes and 165 edges render as a hairball that
    costs tokens and teaches nothing. Collapsed to packages it is a dozen boxes an agent can hold in
    its head, which is the only size that changes behaviour.
    """
    edges: dict[tuple[str, str], int] = {}
    for e in model["graph"]["edges"]:
        src, _, dst = e.partition(" -> ")
        a, b = src.rsplit(".", 1)[0], dst.rsplit(".", 1)[0]
        if a != b:
            edges[(a, b)] = edges.get((a, b), 0) + 1
    lines = ["graph LR"]
    seen: set[str] = set()
    for (a, b) in sorted(edges):
        for n in (a, b):
            if n not in seen:
                seen.add(n)
                lines.append(f'  {n.replace(".", "_")}["{n}"]')
    for (a, b), w in sorted(edges.items()):
        arrow = "==>" if w >= 5 else "-->"
        lines.append(f'  {a.replace(".", "_")} {arrow}|{w}| {b.replace(".", "_")}')
    return "\n".join(lines) + "\n"


def render_markdown(model: dict[str, Any]) -> str:
    c = model["counts"]
    g = model["graph"]
    reg = model["registries"]
    out: list[str] = []
    w = out.append

    w("<!-- title: SYSTEM MAP -->")
    w("<!-- GENERATED by `python3 -m tools.blueprint build` — do not hand-edit. -->")
    w("# System map")
    w("")
    w("**Read this before opening any other file.** It is derived from the tree on every build, so")
    w("it cannot go stale the way a hand-kept overview does. Open only what it points at.")
    w("")
    w(f"`{c['tracked_files']}` tracked files · `{c['python_modules']}` Python modules · "
      f"`{c['import_edges']}` import edges · `{c['documents']}` tracked `.md` files · "
      f"`{c['corpus_guards']}` corpus guards · `{c['health_checks']}` health checks · "
      f"`{c['gate_spine']}` gates · `{c['open_rows']}` open rows "
      f"(**{c['blocking_rows']} blocking**)")
    w("")
    w("> **On that document count.** It is `git ls-files '*.md'` — **every** tracked Markdown file,")
    w("> archived snapshots under `docs/archive/` included. `docs/CHARTER.md` states a different,")
    w("> smaller number for the *corpus*, which excludes those snapshots because they are frozen")
    w("> history rather than live documents. Both are derived and both are right; they answer")
    w("> different questions, and neither used to say which. The charter's number is the one the")
    w("> `counts` guard re-derives on every run.")
    w("")

    w("## Where to look first")
    w("")
    w("| I need to… | Go to |")
    w("|---|---|")
    w("| know what is still open, and what blocks a phase | `docs/process/OPEN_GATES.md` |")
    w("| know the laws | `docs/design/doc-system/RULEBOOK.md` (hash-locked) |")
    w("| know how work is verified and when a phase may end | `docs/process/DEEP_VERIFICATION_PASS.md` |")
    w("| know what already went wrong here | `docs/process/LESSONS.md` |")
    w("| run every gate | `python3 -m tools.health --full` |")
    w("| check the prose corpus against the code | `python3 -m tools.corpus_check` |")
    w("| run the retained counter-examples | `python3 -m unittest discover -s tools/tests -t .` |")
    w("| look up a command, flag, guard, check, schema, figure kind or env var | `blueprint/SURFACES.md` |")
    w("| ask the corpus a JOIN (which module has no document, where did we stop) | `python3 -m tools.blueprint index` then `query` |")
    w("| rebuild this map | `python3 -m tools.blueprint build` |")
    w("")

    system = model.get("system", {})
    if system.get("spec_error"):
        w("## ⛔ The system spec could not be read")
        w("")
        w("Every container, owner and depth below is therefore ABSENT — not empty. Fix this first;")
        w("a map missing its decomposition looks complete and asserts nothing.")
        w("")
        w(f"```\n{system['spec_error']}\n```")
        w("")
    containers = model.get("containers", [])
    if containers:
        w("## The system, in containers")
        w("")
        w("**The only authored part of this map** (`system.spec.json`): which containers to think")
        w("in, what each is for, and the document that owns it. Everything else on this page is")
        w("derived. `python3 -m tools.blueprint verify` exits 1 if any of it stops matching the")
        w("tree — a container naming a package that no longer exists, a module nobody claims, a")
        w("module two containers claim, or an owning document that is not tracked.")
        w("")
        w("`depth` is the C4 ladder of `BUILD_PLAN.md` D4, **measured from evidence, not asserted**,")
        w("and a container is only as deep as its shallowest module. `stopped at` names the rung")
        w("that module failed — which is the actionable half.")
        w("")
        w("| container | owned by | modules | depth | stopped at |")
        w("|---|---|---|---|---|")
        for c in containers:
            at_min: list[str] = list(c.get("shallowest", []))
            # Named distinctly from the `shown` string built for the risky-core table below: both
            # live in this one function, and reusing the name gave them incompatible types.
            at_min_cells: list[str] = [f"`{m}`" for m in at_min[:2]]
            # `+N` rather than a silent cut. The neighbouring gatekeeper column already used `+N`,
            # and this one printed 2 of 13 as though it were the whole list — reading as exhaustive
            # in a table whose own next column disclosed its overflow.
            total_at_min = int(c.get("modules_at_min", len(at_min)))
            if total_at_min > len(at_min_cells):
                at_min_cells.append(f"+{total_at_min - len(at_min_cells)}")
            shallow_cell = ", ".join(at_min_cells) or "—"
            w(f"| **{c['name']}** (`{c['id']}`) | `{c['document']}` | {c.get('modules', 0)} "
              f"| {c.get('depth', 0)} `{c.get('level', '')}` | {shallow_cell} |")
        w("")
        dist = model.get("depth", {}).get("distribution", {})
        if dist:
            levels = model.get("depth", {}).get("levels", [])
            ordered = [(lv, dist[lv]) for lv in levels if lv in dist]
            w("**Where we stopped, across all modules:** "
              + " · ".join(f"`{lv}` {n}" for lv, n in ordered))
            w("")
        unassigned = model.get("ownership", {}).get("unassigned", [])
        if unassigned:
            w(f"**⛔ {len(unassigned)} module(s) no container claims:** "
              + ", ".join(f"`{m}`" for m in unassigned[:10]))
            w("")

    w("## The risky core — modules the most things depend on")
    w("")
    w("Highest in-degree first. A wrong change here breaks the most, so these are the modules that")
    w("earn the most scrutiny and the most counter-examples.")
    w("")
    w("The `gatekeepers` column answers the question an agent actually has before editing: **what")
    w("will refuse me?** It is derived — a registered guard, check or hook is listed when its own")
    w("source reads that module. Full per-module detail is in `blueprint/SYSTEM.json`.")
    w("")
    w("| module | depended on by | depends on | depth | gatekeepers |")
    w("|---|---|---|---|---|")
    gates = model.get("gatekeepers", {})
    depths = model.get("depth", {}).get("modules", {})
    for n in sorted(g["nodes"], key=lambda n: (-n["in"], n["id"]))[:_TOP_CORE]:
        if n["in"] == 0:
            break
        rec = gates.get(n["id"], {})
        names = list(rec.get("guarded_by", []))
        shown = ", ".join(f"`{x}`" for x in names[:3])
        if len(names) > 3:
            shown += f" +{len(names) - 3}"
        level = depths.get(n["id"], {}).get("level", "")
        w(f"| `{n['id']}` | {n['in']} | {n['out']} | `{level}` | {shown or '—'} |")
    w("")

    w("## Packages")
    w("")
    w("| package | modules |")
    w("|---|---|")
    packages: dict[str, int] = {}
    for n in g["nodes"]:
        packages[n["package"]] = packages.get(n["package"], 0) + 1
    for pkg, count in sorted(packages.items(), key=lambda kv: (-kv[1], kv[0]))[:_MAX_PACKAGE_ROWS]:
        w(f"| `{pkg}` | {count} |")
    w("")
    w("Dependency graph: `blueprint/system.mmd` (package level — the module-level graph is in")
    w("`blueprint/SYSTEM.json` under `graph.edges`).")
    w("")

    w("## The gate spine, in adjudication order")
    w("")
    w("Order is load-bearing — it is the order findings are ranked in, and `RULEBOOK` L1 fixes it.")
    w("")
    spine = reg.get("gate_spine", [])
    w("```")
    for i, gate in enumerate(spine, 1):
        w(f"{i:>2}. {gate}")
    w("```")
    w("")

    w("## Registries")
    w("")
    w(f"**Corpus guards** (`tools/corpus_check/guards/`): {', '.join(f'`{x}`' for x in reg.get('corpus_guards', []))}")
    w("")
    checks = reg.get("health_checks", [])
    w(f"**Health checks** (`tools/health/checks.py`): {', '.join(f'`{x}`' for x in sorted(checks))}")
    w("")
    w(f"**Hash-locked rule files** (rulebook `{reg.get('rulebook_version', '?')}`) — editing any of")
    w("these requires the L9 two-step re-baseline:")
    w("")
    for f in reg.get("locked_files", []):
        w(f"- `{f}`")
    w("")

    w("## Documents by classification")
    w("")
    w("| tier | count |")
    w("|---|---|")
    for tier, count in model["document_tiers"].items():
        w(f"| `{tier}` | {count} |")
    w("")

    work = model["open_work"]
    if work:
        w("## Open work")
        w("")
        w("**Addresses, not content.** The first version of this section reproduced the register's")
        w("rows verbatim — same columns, same order — and `cross-doc` immediately reported the copy")
        w("for failing the register's own rules. It was right to: a second table carrying register")
        w("semantics is a second register, and two enforcers of one rule is the defect this engine")
        w("exists to catch (`RULES.md` Rule 2). The register is `docs/process/OPEN_GATES.md`; this")
        w("is only the index into it.")
        w("")
        blocking = [r for r in work if r["disposition"].startswith("BLOCKS_PHASE")]
        scheduled = [r for r in work if r["disposition"].startswith("SCHEDULED")]
        other = [r for r in work if r not in blocking and r not in scheduled]
        if blocking:
            w(f"- **Blocking a phase ({len(blocking)}):** "
              + ", ".join(f"`{r['id']}` ({r['disposition']})" for r in blocking))
        if scheduled:
            w(f"- Deferred to a named phase ({len(scheduled)}): "
              + ", ".join(f"`{r['id']}` {r['disposition']}" for r in scheduled))
        if other:
            w(f"- Open, undeferred ({len(other)}): " + ", ".join(f"`{r['id']}`" for r in other))
        w("")

    if g["unparsed"]:
        w("## Holes in this map")
        w("")
        w("Files the model could not read. Listed rather than skipped, because a map with a silent")
        w("hole is worse than one that admits it.")
        w("")
        for u in g["unparsed"]:
            w(f"- `{u}`")
        w("")

    return "\n".join(out)


def blueprint_files(model: dict[str, Any]) -> dict[str, str]:
    """THE one description of what ``blueprint/`` contains: ``{filename -> exact contents}``.

    Writer and verifier both call this. The alternative — a writer and a checker that each know the
    shape — drifted within hours when it was tried elsewhere in this engine on the same day this was
    written, and reported six files as corrupt on a tree where nothing had changed.
    """
    return {
        "SYSTEM.json": json.dumps(model, indent=2, ensure_ascii=False) + "\n",
        "SYSTEM.md": render_markdown(model),
        "SURFACES.md": render_surfaces(model),
        "COMPLETENESS.md": render_completeness(model),
        "system.mmd": render_mermaid(model),
        "system.d2": render_d2(model),
    }


def render_d2(model: dict[str, Any]) -> str:
    """The container decomposition as `d2` source (`BUILD_PLAN.md` D6).

    **Generated always; rendered only if `d2` is installed.** That split is the whole of D6's
    "optional, never required" rule made mechanical: the *source* is plain text, deterministic and
    diffable, so producing it costs no dependency and cannot break an offline machine. Turning it
    into an SVG needs the binary, and that step degrades through the existing `tool_path` pattern.

    Containers rather than packages, because nested containers are the one shape our own renderers
    do poorly and the exact reason D6 admitted `d2` at all.
    """
    lines = [
        "# GENERATED by `python3 -m tools.blueprint build` — do not hand-edit.",
        "# Render (optional, requires the d2 binary):  d2 blueprint/system.d2 blueprint/system.svg",
        "",
    ]
    containers = model.get("containers", [])
    owner = model.get("ownership", {}).get("owner", {})
    for c in containers:
        cid = c["id"].replace("-", "_")
        lines.append(f'{cid}: "{c["name"]}" {{')
        lines.append(f'  tooltip: "{c["purpose"][:160]}"')
        lines.append(f'  depth: "depth {c.get("depth", 0)} — {c.get("level", "")}"')
        lines.append(f'  modules: "{c.get("modules", 0)} module(s)"')
        lines.append("}")
    # Container-level edges, derived from the module import graph: one arrow per pair that any
    # module import crosses. Weight is the number of real edges behind it, so a reader can see
    # which coupling is structural and which is incidental.
    pairs: dict[tuple[str, str], int] = {}
    for edge in model["graph"]["edges"]:
        src, _, dst = edge.partition(" -> ")
        a, b = owner.get(src, ""), owner.get(dst, "")
        if a and b and a != b:
            pairs[(a, b)] = pairs.get((a, b), 0) + 1
    if pairs:
        lines.append("")
    for (a, b), weight in sorted(pairs.items()):
        lines.append(f'{a.replace("-", "_")} -> {b.replace("-", "_")}: "{weight}"')
    return "\n".join(lines) + "\n"


def render_surfaces(model: dict[str, Any]) -> str:
    """The drill-down: the six things `SYSTEM.md` could not answer, each derived from its owner.

    **Why this is a SEPARATE file.** `SYSTEM.md` is an index and must stay small — an orientation
    map that costs as much to read as the tree it describes has saved nothing. These inventories
    are the opposite shape: nobody reads them front to back, they are looked up. Putting them in
    the index would have doubled the cost of the read that happens every session to serve the reads
    that happen occasionally.
    """
    s = model.get("surfaces", {})
    out: list[str] = []
    w = out.append

    w("<!-- title: SURFACES -->")
    w("<!-- GENERATED by `python3 -m tools.blueprint build` — do not hand-edit. -->")
    w("# Surfaces — the drill-down `SYSTEM.md` deliberately does not carry")
    w("")
    w("Read `blueprint/SYSTEM.md` first; it is the index. **This file is the lookup table behind")
    w("it**, and its contents are not a guess about what might be useful: they are the six things")
    w("the previous phase measured itself having to open the tree for anyway — plus the environment")
    w("surface (§6), which a verifier showed was needed to answer them honestly.")
    w("")
    w("Every section is derived from the artifact that owns it on every build — the schemas from")
    w("the schema files, the configuration from `engine.config.json` plus the resolver's own")
    w("source, the commands from each entry point's `argparse` calls, the guards from the imported")
    w("registry, the figure kinds from `_FIGURE_KINDS`, and each check's assertion from its own")
    w("docstring. Nothing here is maintained by hand.")
    w("")

    w("## 1. Commands and flags — every `argparse` entry point")
    w("")
    w("Scope, stated here rather than only in the preamble: this is derived from the modules that")
    w("construct an `argparse` parser, so it covers every Python entry point and **no** `.mjs` or")
    w("shell one (`OG-202`). The git hooks are documented in `docs/process/THREAT_MODEL.md`.")
    w("")
    for entry in s.get("cli", []):
        w(f"### `{entry['invocation']}`")
        w("")
        if entry.get("global_flags"):
            w(f"Global flags: {', '.join(f'`{f}`' for f in entry['global_flags'])}")
            w("")
        if entry.get("commands"):
            w("| command | does | arguments |")
            w("|---|---|---|")
            for c in entry["commands"]:
                # Help text is published, but a cell is not a man page: one `docgen build` row ran
                # to ~1,100 characters and made the table unreadable. Trimmed per flag, with the
                # full text kept in `SYSTEM.json` for anything that wants it.
                flags = ", ".join(f"`{_trim(f, 90)}`" for f in c["flags"]) or "—"
                w(f"| `{c['command']}` | {c['help'] or '—'} | {flags} |")
            w("")

    w("## 2. Health checks — what each one asserts")
    w("")
    w("In execution order, because the order is part of the answer: a structure check failing")
    w("explains the consistency checks that fail after it.")
    w("")
    w("| # | id | asserts |")
    w("|---|---|---|")
    for c in s.get("health_checks", []):
        w(f"| {c.get('order', '')} | `{c.get('id', '')}` | {c.get('asserts', '')} |")
    w("")

    w("## 3. Corpus guards — the contract, and what registering one costs")
    w("")
    contract = s.get("guard_contract", {})
    if contract:
        w(f"A guard is `{contract.get('signature', '')}`, defined against the result model in")
        w(f"`{contract.get('module', '')}` and registered in `{contract.get('registry', '')}`.")
        w("")
        steps = contract.get("to_register", [])
        w(f"**Registering one costs {_number_word(len(steps))} "
              f"edit{'' if len(steps) == 1 else 's'}:**")
        w("")
        for i, step in enumerate(steps, 1):
            w(f"{i}. {step}")
        w("")
        if contract.get("cost_note"):
            w(f"> {contract['cost_note']}")
            w("")
        w("Invariants every guard is held to:")
        w("")
        for inv in contract.get("invariants", []):
            w(f"- {inv}")
        w("")
    w("| # | guard | module | checks |")
    w("|---|---|---|---|")
    for g in s.get("guards", []):
        w(f"| {g.get('order', '')} | `{g.get('guard', '')}` | `{g.get('module', '')}` | {g.get('checks', '')} |")
    w("")

    w("## 4. Figure kinds")
    w("")
    w("`carries_data` is what RULEBOOK L16 turns into a gate: a kind that puts a number in front of")
    w("a reader must name a resolvable source. It is declared per kind rather than inferred from the")
    w("spec class, because one spec class is shared by four structural kinds that render no quantity.")
    w("")
    w("| kind | carries data | loads with | renders with |")
    w("|---|---|---|---|")
    for f in s.get("figure_kinds", []):
        if "error" in f:
            w(f"| — | — | — | {f['error']} |")
            continue
        mark = "**yes**" if f["carries_data"] else "no"
        w(f"| `{f['kind']}` | {mark} | `{f['loads_with']}` | `{f['renders_with']}` |")
    w("")

    w("## 5. Configuration settings")
    w("")
    w("Precedence is **environment variable > `engine.config.json` > built-in default**.")
    w("")
    w("| section | key | environment variable | default |")
    w("|---|---|---|---|")
    for row in s.get("configuration", []):
        if "error" in row:
            w(f"| — | — | — | {row['error']} |")
            continue
        default = str(row.get("default", ""))
        if len(default) > 90:
            default = default[:87] + "…"
        env_cell = f"`{row['env_var']}`" if row.get("env_var") else "— *(no override)*"
        w(f"| `{row['section']}` | `{row['key']}` | {env_cell} | {default or '—'} |")
    w("")

    w("## 6. Environment variables — every `ENGINE_*` something actually reads")
    w("")
    w("Derived from the files that read a variable, never from a naming convention. An earlier")
    w("version synthesised `ENGINE_<SECTION>_<KEY>` for any setting without a declared override and")
    w("published **8** variables that changed nothing when set; two verifiers measured that")
    w("independently. `ENGINE_CONFIG_PATH` is the one to know — it replaces the entire configuration")
    w("file — and it was missing from this surface entirely until it was rendered here.")
    w("")
    w("| variable | read by |")
    w("|---|---|")
    for row in s.get("environment", []):
        if "error" in row:
            w(f"| — | {row['error']} |")
            continue
        w(f"| `{row['env_var']}` | {', '.join(f'`{x}`' for x in row.get('read_by', []))} |")
    w("")

    w("## 7. JSON schemas")
    w("")
    w("These document a shape; **nothing loads them**, deliberately (`OG-39`) — wiring a validator")
    w("would add a second enforcer of rules three modules already enforce in code. They are listed")
    w("here because a reader who cannot see them assumes the shape is undocumented and re-derives")
    w("it from the dataclass.")
    w("")
    w("| schema | title | required |")
    w("|---|---|---|")
    for sc in s.get("schemas", []):
        if "error" in sc:
            w(f"| `{sc.get('path', '?')}` | — | {sc['error']} |")
            continue
        req = ", ".join(f"`{r}`" for r in sc["required"]) or "—"
        where = sc.get("required_from", "")
        # Say WHERE the required list came from: an array schema keeps its row shape in `$defs`, and
        # a reader who cannot see that reads a ROW's required fields as the DOCUMENT's.
        if where and where != "top level":
            req += f" *(from `{where}`)*"
        w(f"| `{sc['path']}` | {sc['title'] or '—'} | {req} |")
    w("")
    return "\n".join(out)


def render_completeness(model: dict[str, Any]) -> str:
    """The completeness report — *where did we stop*, per node and per document.

    Deliberately a SEPARATE file from `SYSTEM.md`. The index answers "what is here"; this answers
    "how far did we get", which is a different question asked at a different time — usually when
    deciding what to work on next rather than when orienting. Keeping them apart is what lets the
    index stay small enough to read every session.
    """
    c = model.get("completeness", {})
    containers = model.get("containers", [])
    out: list[str] = []
    w = out.append

    w("<!-- title: COMPLETENESS -->")
    w("<!-- GENERATED by `python3 -m tools.blueprint build` — do not hand-edit. -->")
    w("# Completeness — where did we stop")
    w("")
    w("Three states, **derived from evidence** rather than declared:")
    w("")
    # EMITTED FROM THE ONE DEFINITION, never restated here. This table was a hardcoded second copy,
    # and it kept publishing definitions the code had already stopped implementing.
    from tools.blueprint.completeness import STATE_DEFINITIONS

    w("| state | what it means |")
    w("|---|---|")
    for state in c.get("states", []):
        w(f"| `{state}` | {STATE_DEFINITIONS.get(state, '—')} |")
    w("")
    summary = c.get("summary", {})
    total = sum(summary.values()) or 1
    # Rounded, not truncated: `//` turned 3.7% into 3% and the row read 3% + 96% + 0% = 99%.
    w("**Across all nodes:** "
      + " · ".join(
          f"`{state}` {summary.get(state, 0)} ({round(100 * summary.get(state, 0) / total)}%)"
          for state in c.get("states", [])
      ))
    w("")
    # DERIVED, not hardcoded. Three sentences here were emitted unconditionally, so rendering a
    # model with 8 verified and 0 sketched produced a page asserting "`verified` is **0**" directly
    # under a summary line reading 7% — an artifact contradicting itself on the next line, inside a
    # file whose header says GENERATED.
    if not summary.get("verified"):
        w("`verified` is **0**, and that is a measurement rather than an oversight: reaching it needs")
        w("a container-owning document that is governed AND carries a body-certifying stamp still")
        w("covering it, and no document that owns a container is governed yet. That is")
        w("`docs/CHARTER.md`'s purpose 2, still mostly unrealised, stated as a number.")
    else:
        w(f"`verified` is **{summary['verified']}**: those nodes reach rung 4 or deeper and their")
        w("owning document carries a body-certifying stamp that still covers it.")
    w("")
    # Derived, and stated where a reader meets the states: a top state that most of the map cannot
    # reach is a fact about the RULE, not about the work, and it was previously written down nowhere.
    depths_all = model.get("depth", {}).get("modules", {})
    reachable = sum(
        1 for k in c.get("nodes", {}) if int(depths_all.get(k, {}).get("depth", 0)) >= 4
    )
    total_nodes = len(c.get("nodes", {})) or 1
    starved = [
        x["id"] for x in containers
        if not any(int(depths_all.get(m, {}).get("depth", 0)) >= 4
                   for m, cid in model.get("ownership", {}).get("owner", {}).items()
                   if cid == x["id"])
    ]
    w("**It is also unreachable for most of the map today (`OG-207`):** `verified` requires rung 4 or")
    w(f"deeper, rung 3 means *a registered gate reads this module*, and only **{reachable} of {total_nodes}**")
    w(f"nodes are at rung 4 or deeper — so {total_nodes - reachable} cannot reach the top state by any amount")
    w("of documentation work.")
    if starved:
        w(f"{len(starved)} container(s) have no rung-4 module at all "
          f"({', '.join(f'`{x}`' for x in starved)}), so those packages can never report themselves")
        w("`verified` whatever their documents say.")
    w("")

    w("## The ratchet")
    w("")
    w("Each container declares a `depthFloor` in `system.spec.json` — a commitment that it will not")
    w("get shallower. It is checked in **both** directions: measuring below the floor is a")
    w("regression, a floor written beneath the measurement is slack, and a floor written below the")
    w("one committed at `HEAD` is a **loosening** — refused whatever today's measurement says,")
    w("because lowering the measurement and the floor together used to make both look level.")
    w("")
    w("**What it does NOT constrain (`OG-206`):** depth is the `min` over a container's modules, so")
    w("shedding modules can only raise it. A container can lose everything but its shallowest module")
    w("and still report level. **Nothing guards the deletion direction** — `blueprint verify` covers")
    w("modules ADDED and unclaimed, not modules removed — and ratcheting the module count would fire")
    w("on ordinary deletion, which this project has done deliberately before (`OG-73`).")
    w("")
    w(f"Ratchet memory: **{c.get('ratchet_memory', 'unknown')}**.")
    w("")
    w("| container | floor | measured | state of the shallowest module |")
    w("|---|---|---|---|")
    for container in containers:
        floor = container.get("depth_floor")
        shallowest = (container.get("shallowest") or ["—"])[0]
        w(f"| `{container['id']}` | {floor if floor is not None else '**none**'} "
          f"| {container.get('depth', 0)} `{container.get('level', '')}` | `{shallowest}` |")
    w("")
    findings = c.get("floor_findings", [])
    if findings:
        w(f"**⛔ {len(findings)} ratchet finding(s):**")
        w("")
        for f in findings:
            w(f"- {f}")
        w("")
    else:
        w("The ratchet is level: every container declares a floor and measures exactly at it.")
        w("")
    shape_containers = [x["id"] for x in containers if x.get("level") == "shape"]
    if shape_containers:
        named = ", ".join(f"`{x}`" for x in shape_containers)
        w(f"> **{len(shape_containers)} container(s) sit at `shape` because their `__main__.py` is a")
        w(f"> delegation shim** ({named}), which has nothing public by design. Rung 2 asks whether a")
        w("> module's contents are enumerable and tests it by counting public top-level definitions,")
        w("> which a shim legitimately has none of. **Phase 7 decided (`OG-204`) to KEEP this reading:**")
        w("> a shim's `sketched` state carries the accurate `why` — *lacks enumerable* — so a reader")
        w("> sees exactly what is absent (a public surface), and widening rung 2 to admit any non-empty")
        w("> body would move `sketched` to 0 and force four floor-raises in the phase that benefits from")
        w("> the change — the self-serving measurement edit `OG-198`/`OG-204` exist to refuse. The")
        w("> evidence stays a public surface; the decision, not the metric, is the deliverable.")
        w("")

    w("## The document lifecycle")
    w("")
    w("Six steps, each read from the artifact that owns it. **Nothing here is enforced by this")
    w("report** — `classification` gates the tag, `manifest_drift` the wire, `identity` and `stamps`")
    w("the version and the stamp. This says how far each governed document has got.")
    w("")
    steps = c.get("lifecycle_steps", [])
    w("| document | " + " | ".join(f"`{s}`" for s in steps) + " | done |")
    w("|---" * (len(steps) + 2) + "|")
    for doc in c.get("documents", []):
        cells = " | ".join("✅" if doc["steps"].get(s) else "—" for s in steps)
        w(f"| `{doc['path']}` | {cells} | {doc['complete']}/{doc['of']} |")
    w("")
    w("Only governed documents appear: the lifecycle is a contract a document opts into by carrying")
    w("a doc-system header. The count of governed documents is the charter's purpose-2 measurement.")
    w("")

    w("## The shallowest nodes — what to fix first")
    w("")
    w("**Every node short of rung 4**, not only the `sketched` ones. This section listed `sketched`")
    w("alone while claiming to be *the actionable half*, which hid the far larger group: nodes that")
    w("are `documented` but stopped at `gated` or `pinned` — no gate reads them, or no retained")
    w("counter-example names them. Those are the ones worth acting on.")
    w("")
    nodes = c.get("nodes", {})
    depths = model.get("depth", {}).get("modules", {})
    shallow = sorted(
        (k for k, v in nodes.items() if v["state"] != "verified"
         and int(depths.get(k, {}).get("depth", 0)) < 4),
        key=lambda k: (int(depths.get(k, {}).get("depth", 0)), k),
    )
    if shallow:
        by_stop: dict[str, int] = {}
        for node in shallow:
            by_stop[str(depths.get(node, {}).get("stopped_because") or "?")] = (
                by_stop.get(str(depths.get(node, {}).get("stopped_because") or "?"), 0) + 1
            )
        w("**Grouped by the rung they stopped at:** "
          + " · ".join(f"`{k}` {v}" for k, v in sorted(by_stop.items(), key=lambda kv: -kv[1])))
        w("")
        w("| node | state | why |")
        w("|---|---|---|")
        for node in shallow[:40]:
            w(f"| `{node}` | `{nodes[node]['state']}` | {nodes[node]['why']} |")
        if len(shallow) > 40:
            w(f"| … | | **+{len(shallow) - 40} more** — the full list is in `SYSTEM.json` |")
        w("")
    else:
        w("Every node reaches rung 4.")
        w("")
    return "\n".join(out)
